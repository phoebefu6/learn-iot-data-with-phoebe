"""Build assets/iot-sample.js from NASA C-MAPSS FD001 train (real public rows from NASA's simulation).

Usage: python3 -I build_iot_sample.py <path/to/train_FD001.txt> <repo>/assets/iot-sample.js

Source: A. Saxena and K. Goebel (2008), "Turbofan Engine Degradation Simulation Data Set",
NASA Prognostics Data Repository, NASA Ames Research Center. Data set 6 of the PCoE repository.
Every row of FD001 train is kept (100 engines, 20,631 cycles). Flat channels are dropped and
listed. Each kept channel is quantised to at most 90 levels, one printable character per value, units[k].c[i] is channel i of `channels`:
value = lo + level * step, step = max(native resolution, range / 89). json.dumps writes the file.
"""
import json, sys
from collections import OrderedDict

ALPHA = "".join(chr(c) for c in range(35, 127) if chr(c) != "\\")[:90]  # 90 chars, no quote/backslash
NAMES = ["s%d" % i for i in range(1, 22)]
# Table 2 of Saxena et al. (2008) lists 21 sensed outputs in this order; the column-to-symbol
# pairing is the convention the PHM literature uses (reported, the readme numbers them only).
SYMS = ["T2", "T24", "T30", "T50", "P2", "P15", "P30", "Nf", "Nc", "epr", "Ps30", "phi",
        "NRf", "NRc", "BPR", "farB", "htBleed", "Nf_dmd", "PCNfR_dmd", "W31", "W32"]
RES = {"s15": 0.0001, "s21": 0.0001, "s17": 1.0}


def main(src, out):
    rows = [l.split() for l in open(src) if l.strip()]
    units = OrderedDict()
    for r in rows:
        units.setdefault(int(r[0]), []).append(r)
    for u, rs in units.items():
        assert [int(x[1]) for x in rs] == list(range(1, len(rs) + 1)), u
    cols = {n: [float(r[5 + i]) for r in rows] for i, n in enumerate(NAMES)}
    flat, kept, meta = [], [], {}
    for i, n in enumerate(NAMES):
        v = cols[n]
        nuniq = len(set(v))
        mean = sum(v) / len(v)
        sd = (sum((x - mean) ** 2 for x in v) / len(v)) ** 0.5
        if nuniq <= 2:
            flat.append({"ch": n, "sym": SYMS[i], "distinct": nuniq, "min": min(v), "max": max(v),
                         "sd": round(sd, 6)})
            continue
        kept.append(n)
        lo, hi = min(v), max(v)
        res = RES.get(n, 0.01)
        step = max(res, (hi - lo) / 89.0)
        step = round(step, 6)
        meta[n] = {"sym": SYMS[i], "lo": lo, "step": step, "rawSd": round(sd, 6), "distinct": nuniq}
    data = []
    for u, rs in units.items():
        enc = []
        for n in kept:
            j = 5 + NAMES.index(n)
            m = meta[n]
            lv = [int(round((float(r[j]) - m["lo"]) / m["step"])) for r in rs]
            assert max(lv) < 90 and min(lv) >= 0, (n, max(lv))
            enc.append("".join(ALPHA[x] for x in lv))
        data.append({"u": u, "n": len(rs), "c": enc})
    sample = {
        "source": "NASA C-MAPSS FD001 train, Saxena and Goebel (2008), NASA Prognostics Data Repository",
        "note": "Real public rows from NASA's simulation (C-MAPSS), not real engines.",
        "alphabet": ALPHA, "channels": kept, "meta": meta, "flat": flat,
        "settingsNote": "FD001 has one operating condition; operational setting 3 is constant (100.0).",
        "units": data,
    }
    js = ("/* iot-sample.js - generated by materials/build_iot_sample.py with json.dumps. Do not hand-edit.\n"
          "   NASA C-MAPSS FD001 train: 100 simulated engines, every cycle, 14 non-flat channels quantised. */\n"
          "(function (root) {\n  var IOT_SAMPLE = " + json.dumps(sample, separators=(",", ":")) + ";\n"
          "  if (typeof module !== \"undefined\" && module.exports) module.exports = IOT_SAMPLE;\n"
          "  else root.IOT_SAMPLE = IOT_SAMPLE;\n})(this);\n")
    open(out, "w", encoding="utf-8").write(js)
    print("wrote", out, len(js), "bytes;", len(data), "units;", sum(d["n"] for d in data), "rows; kept",
          len(kept), "flat", [f["ch"] for f in flat])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
